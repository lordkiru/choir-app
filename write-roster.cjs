const fs = require('fs')
const p = 'c:/Projects/choir-app/client/src/components/RosterExporter.jsx'
const L = []
const a = (s) => L.push(s)

a("import { useState } from 'react'")
a("import { Copy, CheckCheck, Trophy } from 'lucide-react'")
a("")
a("export default function RosterExporter({ weekLabel, bySong, qualifiedMembers, totalSongs }) {")
a("  const [copied, setCopied] = useState(false)")
a("")
a("  function buildWhatsAppText() {")
a("    const lines = []")
a("    lines.push('🎵 *CHOIR REHEARSAL APPROVALS*')")
a("    lines.push('📅 ' + weekLabel)")
a("    lines.push('')")
a("    lines.push('🎼 *APPROVED SONGS LIST*')")
a("    lines.push('')")
a("    bySong.forEach((g) => {")
a("      lines.push('🎼 *' + g.songTitle + '*')")
a("      if (g.members.length === 0) { lines.push('  _No approvals yet_') }")
a("      else { g.members.forEach((m) => lines.push('  ✅ ' + m.name + ' (' + m.voicePart + ')')) }")
a("      lines.push('')")
a("    })")
a("    lines.push('🏆 *QUALIFIED MEMBERS THIS WEEK*')")
a("    lines.push('_(All ' + totalSongs + ' song' + (totalSongs === 1 ? '' : 's') + ' passed)_')")
a("    lines.push('')")
a("    if (qualifiedMembers.length === 0) { lines.push('  _None yet — keep going!_') }")
a("    else { qualifiedMembers.forEach((m, i) => lines.push('  ' + (i + 1) + '. ' + m.name + ' — ' + m.voicePart)) }")
a("    return lines.join('\\n')")
a("  }")
a("")
a("  async function handleCopy() {")
a("    try { await navigator.clipboard.writeText(buildWhatsAppText()); setCopied(true); setTimeout(() => setCopied(false), 3000) }")
a("    catch { alert('Could not copy. Please copy manually.') }")
a("  }")
a("")
a("  return (")
a("    <div className=\"flex flex-col gap-5\">")
a("      <div className=\"glass p-6 flex flex-col gap-5\">")
a("        <h2 className=\"text-lg font-bold border-b pb-2\" style={{ color: '#9a0f22', borderColor: 'rgba(220,30,60,0.12)' }}>🎼 Approved Songs List</h2>")
a("        {bySong.length === 0 ? <p className=\"text-sm italic\" style={{ color: 'rgba(160,30,50,0.5)' }}>No song approvals yet this week.</p> : (")
a("          bySong.map((group) => (")
a("            <div key={group.songTitle}>")
a("              <p className=\"text-sm font-bold mb-1\" style={{ color: '#9a0f22' }}>{group.songTitle}</p>")
a("              {group.members.length === 0 ? <p className=\"text-sm italic\" style={{ color: 'rgba(160,30,50,0.5)' }}>No approvals yet.</p> : (")
a("                <ul className=\"divide-y\" style={{ borderColor: 'rgba(220,30,60,0.08)' }}>")
a("                  {group.members.map((m, i) => (")
a("                    <li key={i} className=\"py-2 flex items-center justify-between text-sm\">")
a("                      <span className=\"font-medium\" style={{ color: '#1a0005' }}>✅ {m.name}</span>")
a("                      <span className=\"font-semibold\" style={{ color: '#c0152c' }}>{m.voicePart}</span>")
a("                    </li>")
a("                  ))}")
a("                </ul>")
a("              )}")
a("            </div>")
a("          ))")
a("        )}")
a("      </div>")
a("      <div className=\"glass p-6\" style={{ border: '2px solid rgba(220,170,0,0.28)' }}>")
a("        <div className=\"flex items-center gap-2 mb-1\">")
a("          <Trophy size={20} style={{ color: '#b45309' }} />")
a("          <h2 className=\"text-lg font-bold\" style={{ color: '#78350f' }}>Qualified Members This Week</h2>")
a("        </div>")
a("        <p className=\"text-xs mb-4\" style={{ color: 'rgba(120,53,15,0.75)' }}>Submitted and approved in all {totalSongs} song{totalSongs === 1 ? '' : 's'}.</p>")
a("        {qualifiedMembers.length === 0 ? <p className=\"text-sm italic\" style={{ color: 'rgba(120,53,15,0.65)' }}>No one fully qualified yet — keep recording!</p> : (")
a("          <ol className=\"flex flex-col gap-2\">{qualifiedMembers.map((m, i) => (")
a("            <li key={i} className=\"flex items-center justify-between bg-white rounded-xl px-4 py-2.5\" style={{ boxShadow: '0 2px 8px rgba(220,170,0,0.1)', border: '1px solid rgba(220,170,0,0.15)' }}>")
a("              <div className=\"flex items-center gap-3\">")
a("                <span className=\"w-6 h-6 rounded-full flex items-center justify-center text-xs font-bold text-white\" style={{ background: 'linear-gradient(160deg,#f59e0b,#d97706)' }}>{i + 1}</span>")
a("                <span className=\"font-bold\" style={{ color: '#1a0005' }}>{m.name}</span>")
a("              </div>")
a("              <span className=\"text-sm font-semibold\" style={{ color: '#c0152c' }}>{m.voicePart}</span>")
a("            </li>")
a("          ))}</ol>")
a("        )}")
a("      </div>")
a("      <button onClick={handleCopy} className=\"btn-glass-green w-full text-sm py-3 flex items-center justify-center gap-2\">")
a("        {copied ? <><CheckCheck size={18}/> Copied!</> : <><Copy size={18}/> 📱 Copy for WhatsApp</>}")
a("      </button>")
a("    </div>")
a("  )")
a("}")

fs.writeFileSync(p, L.join('\n'), 'utf8')
console.log('RosterExporter written:', L.length, 'lines')
