const fs = require('fs')
const p = 'c:/Projects/choir-app/client/src/pages/Login.jsx'
const L = []
const a = (s) => L.push(s)

a("import { useState } from 'react'")
a("import { Link, useNavigate } from 'react-router-dom'")
a("import { login } from '../api'")
a("import { useAuth } from '../contexts/AuthContext'")
a("import { Music, Mail, Lock } from 'lucide-react'")
a("")
a("export default function Login() {")
a("  const { loginUser } = useAuth()")
a("  const navigate = useNavigate()")
a("  const [form, setForm] = useState({ email: '', password: '' })")
a("  const [error, setError] = useState('')")
a("  const [busy, setBusy] = useState(false)")
a("")
a("  async function handleSubmit(e) {")
a("    e.preventDefault()")
a("    setBusy(true); setError('')")
a("    try { const { data } = await login(form); loginUser(data.token); navigate('/') }")
a("    catch (err) { setError(err.response?.data?.error || 'Login failed.') }")
a("    finally { setBusy(false) }")
a("  }")
a("")
a("  return (")
a("    <div className=\"min-h-screen flex items-center justify-center p-4\">")
a("      <div className=\"glass w-full max-w-sm p-8 flex flex-col gap-6\">")
a("        <div className=\"text-center flex flex-col items-center gap-3\">")
a("          <div className=\"w-16 h-16 rounded-2xl flex items-center justify-center\" style={{ background: 'linear-gradient(160deg,#e8203a,#9a0f22)', boxShadow: '0 8px 28px rgba(220,20,50,0.4),inset 0 1px 0 rgba(255,180,180,0.4)' }}>")
a("            <Music size={28} className=\"text-white\" />")
a("          </div>")
a("          <div>")
a("            <h1 className=\"text-2xl font-bold text-glow\" style={{ color: '#9a0f22' }}>Welcome back</h1>")
a("            <p className=\"text-sm mt-1\" style={{ color: 'rgba(160,30,50,0.6)' }}>Sign in to ChoirApp</p>")
a("          </div>")
a("        </div>")
a("        <form onSubmit={handleSubmit} className=\"flex flex-col gap-4\">")
a("          <div className=\"flex flex-col gap-1.5\">")
a("            <label className=\"text-xs font-semibold flex items-center gap-1.5\" style={{ color: '#9a0f22' }}><Mail size={12} /> Email</label>")
a("            <input type=\"email\" required value={form.email} onChange={(e) => setForm({ ...form, email: e.target.value })} className=\"input-glass\" placeholder=\"you@example.com\" />")
a("          </div>")
a("          <div className=\"flex flex-col gap-1.5\">")
a("            <label className=\"text-xs font-semibold flex items-center gap-1.5\" style={{ color: '#9a0f22' }}><Lock size={12} /> Password</label>")
a("            <input type=\"password\" required value={form.password} onChange={(e) => setForm({ ...form, password: e.target.value })} className=\"input-glass\" placeholder=\"••••••••\" />")
a("          </div>")
a("          {error && <div className=\"rounded-xl px-4 py-3 text-sm\" style={{ background: 'rgba(220,30,60,0.08)', border: '1px solid rgba(220,30,60,0.25)', color: '#9a0f22' }}>{error}</div>}")
a("          <button type=\"submit\" disabled={busy} className=\"btn-glass w-full text-sm py-3 mt-1\">{busy ? 'Signing in\u2026' : 'Sign in'}</button>")
a("        </form>")
a("        <p className=\"text-center text-sm\" style={{ color: 'rgba(160,30,50,0.6)' }}>")
a("          No account? <Link to=\"/register\" className=\"font-semibold hover:underline\" style={{ color: '#c0152c' }}>Register</Link>")
a("        </p>")
a("      </div>")
a("    </div>")
a("  )")
a("}")

fs.writeFileSync(p, L.join('\n'), 'utf8')
