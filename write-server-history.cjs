const fs = require('fs')
const p = 'c:/Projects/choir-app/server/routes/history.js'
const L = []
const a = (s) => L.push(s)

a("const router = require('express').Router()")
a("const { protect } = require('../middleware/auth')")
a("const ApprovalRecord = require('../models/ApprovalRecord')")
a("")
a("router.get('/', protect, async (req, res) => {")
a("  try {")
a("    const { search, from, to } = req.query")
a("    const dateFilter = {}")
a("    if (from) dateFilter['$gte'] = new Date(from)")
a("    if (to) { const d = new Date(to); d.setHours(23,59,59,999); dateFilter['$lte'] = d }")
a("    const recordFilter = {}")
a("    if (Object.keys(dateFilter).length) recordFilter.approvedAt = dateFilter")
a("    if (search) {")
a("      recordFilter['$or'] = [")
a("        { weekLabel: { '$regex': search, '$options': 'i' } },")
a("        { songTitle: { '$regex': search, '$options': 'i' } },")
a("        { memberName: { '$regex': search, '$options': 'i' } },")
a("      ]")
a("    }")
a("    const records = await ApprovalRecord.find(recordFilter).sort({ approvedAt: -1 }).lean()")
a("    const weekMap = {}")
a("    records.forEach((r) => {")
a("      if (!weekMap[r.weekLabel]) weekMap[r.weekLabel] = { weekLabel: r.weekLabel, earliestDate: r.approvedAt, songs: {}, memberSongMap: {} }")
a("      const w = weekMap[r.weekLabel]")
a("      const sk = String(r.songId)")
a("      if (!w.songs[sk]) w.songs[sk] = { title: r.songTitle, approvedCount: 0 }")
a("      w.songs[sk].approvedCount++")
a("      const mk = String(r.memberId)")
a("      if (!w.memberSongMap[mk]) w.memberSongMap[mk] = { name: r.memberName, voicePart: r.voicePart, songs: new Set() }")
a("      w.memberSongMap[mk].songs.add(sk)")
a("    })")
a("    const weeks = Object.values(weekMap).map((w) => {")
a("      const totalSongs = Object.keys(w.songs).length")
a("      const qualifiedMembers = Object.values(w.memberSongMap)")
a("        .filter((m) => m.songs.size >= totalSongs)")
a("        .map((m) => ({ name: m.name, voicePart: m.voicePart }))")
a("        .sort((a, b) => a.name.localeCompare(b.name))")
a("      return { weekLabel: w.weekLabel, earliestDate: w.earliestDate, totalSongs, songs: Object.values(w.songs).sort((a, b) => a.title.localeCompare(b.title)), qualifiedCount: qualifiedMembers.length, qualifiedMembers }")
a("    }).sort((a, b) => new Date(b.earliestDate) - new Date(a.earliestDate))")
a("    const pqMap = {}")
a("    Object.values(weekMap).forEach((w) => {")
a("      const t = Object.keys(w.songs).length")
a("      Object.entries(w.memberSongMap).forEach(([id, m]) => {")
a("        if (m.songs.size >= t) { if (!pqMap[id]) pqMap[id] = { name: m.name, voicePart: m.voicePart, weeksQualified: 0 }; pqMap[id].weeksQualified++ }")
a("      })")
a("    })")
a("    const ppMap = {}")
a("    Object.values(weekMap).forEach((w) => Object.entries(w.memberSongMap).forEach(([id, m]) => {")
a("      if (!ppMap[id]) ppMap[id] = { name: m.name, voicePart: m.voicePart, weeksParticipated: 0 }; ppMap[id].weeksParticipated++")
a("    }))")
a("    const qIds = new Set(Object.keys(pqMap))")
a("    const periodQualified = Object.values(pqMap).sort((a, b) => b.weeksQualified - a.weeksQualified || a.name.localeCompare(b.name))")
a("    const neverQualified = Object.entries(ppMap).filter(([id]) => !qIds.has(id)).map(([, m]) => ({ name: m.name, voicePart: m.voicePart, weeksParticipated: m.weeksParticipated })).sort((a, b) => a.name.localeCompare(b.name))")
a("    res.json({ weeks, total: weeks.length, periodQualified, neverQualified })")
a("  } catch (err) { res.status(500).json({ error: err.message }) }")
a("})")
a("")
a("module.exports = router")

fs.writeFileSync(p, L.join('\n'), 'utf8')
console.log('history.js written:', L.length, 'lines')
