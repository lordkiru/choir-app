const fs = require('fs')
const p = 'c:/Projects/choir-app/client/src/components/AudioRecorder.jsx'
const L = []
const a = (s) => L.push(s)

a("import { useState, useRef, useEffect } from 'react'")
a("import { Mic, Square, Upload, X, Headphones } from 'lucide-react'")
a("")
a("export default function AudioRecorder({ song, onSubmit, onClose }) {")
a("  const [phase, setPhase] = useState('idle')")
a("  const [error, setError] = useState('')")
a("  const [refVolume, setRefVolume] = useState(0.7)")
a("  const [micVolume, setMicVolume] = useState(1.0)")
a("  const [elapsed, setElapsed] = useState(0)")
a("  const [blob, setBlob] = useState(null)")
a("  const [micLevel, setMicLevel] = useState(0)")
a("  const audioCtxRef = useRef(null)")
a("  const gainNodeRef = useRef(null)")
a("  const micGainRef = useRef(null)")
a("  const analyserRef = useRef(null)")
a("  const rafRef = useRef(null)")
a("  const mediaRecorderRef = useRef(null)")
a("  const chunksRef = useRef([])")
a("  const refAudioElRef = useRef(null)")
a("  const timerRef = useRef(null)")
a("  const previewRef = useRef(null)")
a("")
a("  useEffect(() => { if (gainNodeRef.current) gainNodeRef.current.gain.value = refVolume }, [refVolume])")
a("  useEffect(() => { if (micGainRef.current) micGainRef.current.gain.value = micVolume }, [micVolume])")
a("  useEffect(() => () => stopEverything(), [])")
a("")
a("  function startMeterLoop(analyser) {")
a("    const data = new Uint8Array(analyser.frequencyBinCount)")
a("    function tick() {")
a("      analyser.getByteTimeDomainData(data)")
a("      let sum = 0")
a("      for (let i = 0; i < data.length; i++) { const v = (data[i] - 128) / 128; sum += v * v }")
a("      setMicLevel(Math.min(100, Math.round(Math.sqrt(sum / data.length) * 400)))")
a("      rafRef.current = requestAnimationFrame(tick)")
a("    }")
a("    rafRef.current = requestAnimationFrame(tick)")
a("  }")
a("  function stopMeterLoop() { if (rafRef.current) cancelAnimationFrame(rafRef.current); setMicLevel(0) }")
a("  function stopEverything() {")
a("    clearInterval(timerRef.current); stopMeterLoop()")
a("    if (mediaRecorderRef.current && mediaRecorderRef.current.state !== 'inactive') mediaRecorderRef.current.stop()")
a("    if (refAudioElRef.current) { refAudioElRef.current.pause(); refAudioElRef.current.src = '' }")
a("    if (audioCtxRef.current && audioCtxRef.current.state !== 'closed') audioCtxRef.current.close()")
a("  }")
a("  async function startRecording() {")
a("    setError(''); setElapsed(0); chunksRef.current = []")
a("    try {")
a("      const micStream = await navigator.mediaDevices.getUserMedia({ audio: true, video: false })")
a("      const ctx = new AudioContext()")
a("      audioCtxRef.current = ctx")
a("      const destination = ctx.createMediaStreamDestination()")
a("      const micSource = ctx.createMediaStreamSource(micStream)")
a("      const micGain = ctx.createGain()")
a("      micGain.gain.value = micVolume; micGainRef.current = micGain")
a("      const analyser = ctx.createAnalyser()")
a("      analyser.fftSize = 256; analyserRef.current = analyser")
a("      micSource.connect(micGain); micGain.connect(analyser); micGain.connect(destination)")
a("      if (song.referenceAudioUrl) {")
a("        const refEl = new Audio()")
a("        refEl.crossOrigin = 'anonymous'; refEl.src = song.referenceAudioUrl; refAudioElRef.current = refEl")
a("        const gain = ctx.createGain()")
a("        gain.gain.value = refVolume; gainNodeRef.current = gain")
a("        ctx.createMediaElementSource(refEl).connect(gain)")
a("        gain.connect(destination); gain.connect(ctx.destination)")
a("        refEl.play().catch(() => {})")
a("      }")
a("      const recorder = new MediaRecorder(destination.stream, { mimeType: 'audio/webm' })")
a("      mediaRecorderRef.current = recorder")
a("      recorder.ondataavailable = (e) => { if (e.data.size > 0) chunksRef.current.push(e.data) }")
a("      recorder.onstop = () => { stopMeterLoop(); setBlob(new Blob(chunksRef.current, { type: 'audio/webm' })); setPhase('preview') }")
a("      recorder.start(250)")
a("      timerRef.current = setInterval(() => setElapsed((s) => s + 1), 1000)")
a("      startMeterLoop(analyser); setPhase('recording')")
a("    } catch (err) { setError('Microphone access denied: ' + err.message) }")
a("  }")
a("  function stopRecording() {")
a("    clearInterval(timerRef.current); stopMeterLoop()")
a("    if (refAudioElRef.current) refAudioElRef.current.pause()")
a("    if (mediaRecorderRef.current?.state !== 'inactive') mediaRecorderRef.current.stop()")
a("  }")
a("  function handleDiscard() { stopEverything(); setBlob(null); setPhase('idle') }")
a("  async function handleSubmit() {")
a("    if (!blob) return")
a("    setPhase('uploading'); setError('')")
a("    try { await onSubmit(blob, song._id) }")
a("    catch (err) { setError(err.response?.data?.error || err.message); setPhase('preview') }")
a("  }")
a("  const fmt = (s) => String(Math.floor(s / 60)).padStart(2,'0') + ':' + String(s % 60).padStart(2,'0')")
a("  const BAR_COUNT = 10")
a("  const activeBars = Math.round((micLevel / 100) * BAR_COUNT)")
a("  const barColor = (i) => i >= 8 ? '#dc2626' : i >= 6 ? '#f59e0b' : '#16a34a'")
a("  const levelLabel = micLevel < 5 ? 'Silent' : micLevel < 30 ? 'Low' : micLevel < 70 ? 'Good' : micLevel < 90 ? 'Strong' : 'Too loud!'")

fs.writeFileSync(p, L.join('\n'), 'utf8')
console.log('AudioRecorder part1:', L.length)
