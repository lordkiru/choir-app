const fs = require('fs')

// ── Register.jsx ──
const reg = []
const r = (s) => reg.push(s)
r("import { useState } from 'react'")
r("import { Link, useNavigate } from 'react-router-dom'")
r("import { register } from '../api'")
r("import { useAuth } from '../contexts/AuthContext'")
r("import { Music } from 'lucide-react'")
r("const VOICE_PARTS = ['Soprano', 'Alto', 'Tenor', 'Bass']")
r("export default function Register() {")
r("  const { loginUser } = useAuth(); const navigate = useNavigate()")
r("  const [form, setForm] = useState({ name: '', email: '', password: '', voicePart: '' })")
r("  const [error, setError] = useState(''); const [busy, setBusy] = useState(false)")
r("  async function handleSubmit(e) {")
r("    e.preventDefault()")
r("    if (!form.voicePart) return setError('Please select your voice part.')")
r("    setBusy(true); setError('')")
r("    try { const { data } = await register(form); loginUser(data.token); navigate('/') }")
r("    catch (err) { setError(err.response?.data?.error || 'Registration failed.') }")
r("    finally { setBusy(false) }")
r("  }")
r("  return (")
r("    <div className=\"min-h-screen flex items-center justify-center p-4\">")
r("      <div className=\"glass w-full max-w-sm p-8 flex flex-col gap-6\">")
r("        <div className=\"text-center flex flex-col items-center gap-3\">")
r("          <div className=\"w-16 h-16 rounded-2xl flex items-center justify-center\" style={{ background: 'linear-gradient(160deg,#e8203a,#9a0f22)', boxShadow: '0 8px 28px rgba(220,20,50,0.4),inset 0 1px 0 rgba(255,180,180,0.4)' }}>")
r("            <Music size={28} className=\"text-white\" />")
r("          </div>")
r("          <div><h1 className=\"text-2xl font-bold text-glow\" style={{ color: '#9a0f22' }}>Join ChoirApp</h1>")
r("          <p className=\"text-sm mt-1\" style={{ color: 'rgba(160,30,50,0.6)' }}>Create your account</p></div>")
r("        </div>")
r("        <form onSubmit={handleSubmit} className=\"flex flex-col gap-3\">")
r("          {[{label:'Full name',key:'name',type:'text',ph:'Jane Doe'},{label:'Email',key:'email',type:'email',ph:'you@example.com'},{label:'Password',key:'password',type:'password',ph:'••••••••'}].map(({label,key,type,ph})=>(")
r("            <div key={key} className=\"flex flex-col gap-1\">")
r("              <label className=\"text-xs font-semibold\" style={{ color: '#9a0f22' }}>{label}</label>")
r("              <input type={type} required value={form[key]} onChange={(e)=>setForm({...form,[key]:e.target.value})} className=\"input-glass\" placeholder={ph} />")
r("            </div>")
r("          ))}")
r("          <div className=\"flex flex-col gap-1\">")
r("            <label className=\"text-xs font-semibold\" style={{ color: '#9a0f22' }}>Voice part</label>")
r("            <select value={form.voicePart} onChange={(e)=>setForm({...form,voicePart:e.target.value})} className=\"input-glass\" style={{ cursor:'pointer' }}>")
r("              <option value=\"\">Select your part\u2026</option>")
r("              {VOICE_PARTS.map((p)=><option key={p} value={p}>{p}</option>)}")
r("            </select>")
r("          </div>")
r("          {error && <div className=\"rounded-xl px-4 py-3 text-sm\" style={{ background:'rgba(220,30,60,0.08)',border:'1px solid rgba(220,30,60,0.25)',color:'#9a0f22' }}>{error}</div>}")
r("          <button type=\"submit\" disabled={busy} className=\"btn-glass w-full text-sm py-3 mt-1\">{busy ? 'Creating account\u2026' : 'Create account'}</button>")
r("        </form>")
r("        <p className=\"text-center text-sm\" style={{ color: 'rgba(160,30,50,0.6)' }}>")
r("          Already registered? <Link to=\"/login\" className=\"font-semibold hover:underline\" style={{ color: '#c0152c' }}>Sign in</Link>")
r("        </p>")
r("      </div>")
r("    </div>")
r("  )")
r("}")
fs.writeFileSync('c:/Projects/choir-app/client/src/pages/Register.jsx', reg.join('\n'), 'utf8')
console.log('Register.jsx done')
